    private static final Logger LOG = LoggerFactory.getLogger();

    private ScannerConfig scannerConfig;

    public EchoServerFetcher(ScannerConfig scannerConfig) {
        this.scannerConfig = scannerConfig;
    }

    @CheckReturnValue
    @NonNull
    @Override
    public String getId() {
        return "fetcher.echoServerFetcher";
    }

    @CheckReturnValue
    @Nullable
    @Override
    public Object scan(ScanningSubject subject) {
        try (Socket socket = new Socket()) {
            socket.connect(new InetSocketAddress(subject.getAddress(), ECHO_PORT), subject.getAdaptedPortTimeout());
            socket.setTcpNoDelay(true);
            socket.setSoTimeout(scannerConfig.portTimeout * 2);
            socket.setSoLinger(true, 0);

            OutputStream os = socket.getOutputStream();
            os.write(PAYLOAD);
            os.flush();

            byte[] echoResponse = socket.getInputStream().readNBytes(PAYLOAD.length);
            int firstMismatch = Arrays.mismatch(echoResponse, PAYLOAD);

            if (firstMismatch == -1 /* no mismatch */) {
                subject.setResultType(ResultType.WITH_PORTS);
                return Labels.getLabel("text.fetcher.echoServerFetcher.true");
            } else {
                return String.format("%s (%d)", Labels.getLabel("text.fetcher.echoServerFetcher.false"), firstMismatch);
            }
        } catch (ConnectException e) {
            // no connection
        } catch (SocketTimeoutException e) {
            // no information
        } catch (SocketException e) {
            // connection reset
        } catch (IOException e) {
            LOG.log(Level.FINE, subject.getAddress().toString(), e);
        }
        return null;
    }

